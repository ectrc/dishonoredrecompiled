// DISHONORED(written): agent EC. Retail's operator<<(UObject*&) (2013 rva 0x60c930) looks a remembered
// record up with StaticFindObjectFast and, failing that, constructs it from the class, outer and name the
// record carries - and it takes the outer straight out of m_Objects, because in the session that wrote the
// save every record's outer was resident. Here a record's outer can be another record this session does not
// have (Dishonored0.sav's DisConversation_InGameData_Base_147 inside DisDialogTree_InGameBind_57: both are
// built by playing), so the outer is resolved the same way, one level up. StaticConstructObject with no outer
// is a hard error - "Object is not packaged" - which says nothing about which record it was, so a record
// whose outer cannot be resolved at all returns NULL and the caller stops the restore by name.
UObject* FLevelLoader::ResolveRecord( WORD _Index )
{
	if( _Index == 0 || _Index >= m_Objects.Num() )
	{
		return NULL;
	}
	if( m_Objects(_Index) != NULL )
	{
		return m_Objects(_Index);
	}
	const FObjectRef* pFound = m_NotFoundObjects.Find( _Index );
	if( pFound == NULL || pFound->m_pClass == NULL )
	{
		return NULL;
	}
	const FObjectRef Ref = *pFound;
	m_NotFoundObjects.Remove( _Index );

	UObject* pOuter = ResolveRecord( Ref.m_OuterIndex );
	if( pOuter == NULL && Ref.m_OuterIndex != 0 )
	{
		return NULL;
	}
	UObject* pObject = UObject::StaticFindObjectFast( Ref.m_pClass, pOuter, Ref.m_Name );
	if( pObject == NULL && pOuter != NULL )
	{
		pObject = UObject::StaticConstructObject( Ref.m_pClass, pOuter, Ref.m_Name );
	}
	m_Objects(_Index) = pObject;
	return pObject;
}

// DISHONORED(port): 2013 rva 0x60c930 (2012 0x653700). A WORD dictionary index; the top bit means the
// object belongs to an unshared sub-level, so its state is not in this stream.
FArchive& FLevelLoader::operator<<( UObject*& _rpObject )
{
	if( m_bAborted )
	{
		_rpObject = NULL;
		return *this;
	}

	WORD ObjIndex = 0;
	ByteOrderSerialize( &ObjIndex, sizeof(ObjIndex) );
	UBOOL bDeferred = FALSE;
	if( ( ObjIndex & 0x8000 ) != 0 )
	{
		ObjIndex &= 0x7FFF;
		bDeferred = TRUE;
	}

	if( ObjIndex == 0 )
	{
		_rpObject = NULL;
		return *this;
	}

	_rpObject = ResolveRecord( ObjIndex );

	if( m_DebugStreamObjects > 0 && ++m_DebugStreamSeen <= m_DebugStreamObjects )
	{
		warnf( TEXT("DisStream %5d: byte %6d ref %5d%s -> %s"), m_DebugStreamSeen, Tell(), (INT)ObjIndex,
			bDeferred ? TEXT(" (unshared)") : TEXT(""),
			_rpObject != NULL ? *_rpObject->GetPathName() : TEXT("<not in this session>") );
	}

	if( bDeferred )
	{
		// the reference belongs to an unshared sub-level: its state is in that level's own stream, not here
		GSaveLoadCensus.m_ObjectsSkipped++;
		return *this;
	}
	if( _rpObject == NULL )
	{
		// retail cannot reach this - ShouldLoadObject dereferences the object with no NULL check, because in
		// the session that wrote the save everything the dictionary named was resident. Here it is common, and
		// skipping the object reads none of the bytes retail wrote for it, so the rest of the stream is lost.
		GSaveLoadCensus.m_NullObjects++;
		if( !GSaveLoadCensus.m_bDesynchronised )
		{
			GSaveLoadCensus.m_bDesynchronised = TRUE;
			warnf( NAME_Warning, TEXT("DisSaveLoad: stopping the level restore at dictionary index %d, which resolved to no live object in this session: retail wrote that object's state inline with no length prefix, so its bytes cannot be skipped. %d objects were restored first."),
				(INT)ObjIndex, GSaveLoadCensus.m_ObjectsRestored );
		}
		m_bAborted = TRUE;
		return *this;
	}

	// the safety net: retail wrote this object's state with the first override in its class chain. If that
	// is one this tree does not have, reading on would misread every object after it.
	FString BlockingClass;
	const EDisSaveClassState State = DisClassifySaveClass( _rpObject->GetClass(), BlockingClass );
	if( State == DSCS_Unported )
	{
		GSaveLoadCensus.m_UnportedClasses++;
		if( !GSaveLoadCensus.m_bDesynchronised )
		{
			GSaveLoadCensus.m_bDesynchronised = TRUE;
			warnf( NAME_Warning, TEXT("DisSaveLoad: stopping the level restore at '%s' (%s): its GameLoad is one of the %d retail overrides this tree has not ported, and the object stream carries no length prefix, so reading on would desynchronise it. %d objects were restored first."),
				*_rpObject->GetPathName(), *BlockingClass,
				(INT)ARRAY_COUNT(GDisUnportedGameLoadClasses), GSaveLoadCensus.m_ObjectsRestored );
		}
		m_bAborted = TRUE;
		_rpObject = NULL;
		return *this;
	}

	if( ShouldLoadObject( _rpObject ) )
	{
		m_LoadedObjects.Add( _rpObject );
		GSaveLoadCensus.m_ObjectsRestored++;
		_rpObject->GameLoad( *this, m_Location );
		return *this;
	}

	// not saveable here - but is that retail's answer or a missing IsSaveable? When retail treats the class
	// as an entry point and this tree declares none in that chain, retail's answer is the inline `return
	// TRUE` its linker folded onto UObject::IsRefSaveable, which is why those 59 have no PDB symbol. So the
	// object's state IS in the stream, and the right thing is to read it, not to stop: the gate that decides
	// whether it CAN be read is the GameLoad one above. Agent EC: agent ED stopped here instead, which is
	// what a tree with fourteen override bodies should do and what a tree with thirty-eight should not.
	FString EntryClass;
	if( !m_LoadedObjects.Contains( _rpObject ) && !DisIsSaveableAnswerTrusted( _rpObject->GetClass(), EntryClass ) )
	{
		GSaveLoadCensus.m_UntrustedSkips++;
		m_LoadedObjects.Add( _rpObject );
		GSaveLoadCensus.m_ObjectsRestored++;
		_rpObject->GameLoad( *this, m_Location );
		return *this;
	}

	GSaveLoadCensus.m_ObjectsSkipped++;
	return *this;
}

// DISHONORED(port): 2013 rva 0x607b30 (2012 0x64d120)
UBOOL FLevelLoader::ShouldLoadObject( UObject* _pObject )
{
	return _pObject->IsSaveable( m_Location ) && !m_LoadedObjects.Contains( _pObject );
}

// DISHONORED(port): 2013 rva 0x60bbc0 (2012 0x6516f0) - every restored object's PostGameLoad, once the
// whole level state is in.
void FLevelLoader::NotifyPostGameLoad()
{
	for( TSet<UObject*>::TConstIterator It(m_LoadedObjects); It; ++It )
	{
		(*It)->PostGameLoad( m_Location );
		GSaveLoadCensus.m_PostGameLoad++;
	}
}

// DISHONORED(port): 2013 rva 0x602760 (2012 0x649130) - re-link the level's Kismet and re-fire the
// "Loaded and Visible" output of its Level Loaded event, which is output 3.
void InitializeSequencePostLoad( USequence* _pSequence )
{
	if( _pSequence == NULL )
	{
		return;
	}
	_pSequence->InitializeSequence();
	for( INT ObjIdx = 0; ObjIdx < _pSequence->SequenceObjects.Num(); ObjIdx++ )
	{
		USeqEvent_LevelLoaded* pLevelLoaded = Cast<USeqEvent_LevelLoaded>( _pSequence->SequenceObjects(ObjIdx) );
		if( pLevelLoaded == NULL )
		{
			continue;
		}
		if( pLevelLoaded->OutputLinks.Num() > 3 && pLevelLoaded->OutputLinks(3).Links.Num() > 0 )
		{
			TArray<INT> ActivateIndices;
			ActivateIndices.AddItem( 3 );
			pLevelLoaded->TriggerCount = 0;
			pLevelLoaded->CheckActivate( GWorld->GetWorldInfo(), NULL, FALSE, &ActivateIndices, FALSE );
		}
	}
}

