// DISHONORED(port): 2013 rva 0x613db0 (2012 0x659b50). The level state whose name matches this level is
// restored and then discarded, because a state is consumed once.
void FGameState::LoadLevel( ULevel* _pLevel )
{
	const FName LevelName = DisGetLevelName( _pLevel );
	const INT LevelIndex = findLevelIndex( LevelName );
	if( LevelIndex == INDEX_NONE )
	{
		return;
	}

	FLevelState& LevelState = *m_LevelStates(LevelIndex);
	const FName PackageName = ( _pLevel != NULL && _pLevel->GetOutermost() != NULL )
		? _pLevel->GetOutermost()->GetFName() : FName(NAME_None);

	WORD NumObjects			= 0;
	WORD NumSavedObjects	= 0;
	UBOOL bReadUnshared		= FALSE;
	if( LevelState.m_PackageName == PackageName )
	{
		NumObjects			= LevelState.m_NumObjects;
		NumSavedObjects		= LevelState.m_NumSavedObjects;
		bReadUnshared		= TRUE;
	}
	else
	{
		NumObjects			= LevelState.m_NumSharedObjects;
		NumSavedObjects		= LevelState.m_NumSavedSharedObjects;
		bReadUnshared		= FALSE;
	}

	m_bIsLoadingLevelState = TRUE;
	{
		FLevelLoader LevelLoader( m_StringDictionary, LevelState.m_CompressedObjectData,
			LevelState.m_CompressedObjectDictionary, _pLevel, LevelState.m_PackageName,
			LevelState.m_Location, NumObjects, NumSavedObjects, bReadUnshared, LevelState.m_SaveVersion );
		discardLevelState( LevelIndex );
		LevelLoader.NotifyPostGameLoad();
	}
	m_bIsLoadingLevelState = FALSE;
}

// DISHONORED(port): 2013 rva 0x5fe820 (2012 0x644280)
UBOOL FGameState::ContainsObjectState( UObject* _pObject ) const
{
	if( _pObject == NULL )
	{
		return FALSE;
	}
	ULevel* pLevel = _pObject->GetTypedOuter<ULevel>();
	if( pLevel == NULL )
	{
		pLevel = DisGetCurrentLevel();
	}
	return findLevelIndex( DisGetLevelName( pLevel ) ) != INDEX_NONE;
}

