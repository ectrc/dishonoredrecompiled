enum EDisSaveClassState
{
	DSCS_NoOverride		= 0,	// retail's UObject body runs: zero bytes either way, always safe
	DSCS_Ported			= 1,	// the body that runs is one this tree has
	DSCS_Unported		= 2,	// retail wrote bytes this tree cannot read
};

static UBOOL DisNameInList( const FString& _rName, const TCHAR** _pList, INT _Num )
{
	for( INT Idx = 0; Idx < _Num; Idx++ )
	{
		if( _rName == _pList[Idx] )
		{
			return TRUE;
		}
	}
	return FALSE;
}

/** DISHONORED(written): the first class in the chain with a GameSave/GameLoad body of its own decides which
    body runs, so that is the one that has to be ported. Cached per UClass: a mission save reaches this
    twelve thousand times. */
static EDisSaveClassState DisClassifySaveClass( UClass* _pClass, FString& _rOutClass )
{
	static TMap<UClass*,INT>	ClassStates;
	static TMap<UClass*,FString>	ClassBlockers;

	if( _pClass == NULL )
	{
		return DSCS_NoOverride;
	}
	const INT* pCached = ClassStates.Find( _pClass );
	if( pCached != NULL )
	{
		if( *pCached == DSCS_Unported )
		{
			_rOutClass = *ClassBlockers.Find( _pClass );
		}
		return (EDisSaveClassState)*pCached;
	}

	EDisSaveClassState State = DSCS_NoOverride;
	FString Blocker;
	for( UClass* pWalk = _pClass; pWalk != NULL; pWalk = pWalk->GetSuperClass() )
	{
		const FString Name = pWalk->GetName();
		if( DisNameInList( Name, GDisPortedGameLoadClasses, ARRAY_COUNT(GDisPortedGameLoadClasses) ) )
		{
			State = DSCS_Ported;
			break;
		}
		if( DisNameInList( Name, GDisUnportedGameLoadClasses, ARRAY_COUNT(GDisUnportedGameLoadClasses) ) )
		{
			State = DSCS_Unported;
			Blocker = Name;
			break;
		}
	}
	ClassStates.Set( _pClass, State );
	if( State == DSCS_Unported )
	{
		ClassBlockers.Set( _pClass, Blocker );
		_rOutClass = Blocker;
	}
	return State;
}

/** DISHONORED(written): is this tree's IsSaveable answer for this object retail's answer? Retail treats 372
    classes as save entry points, 59 of them through an inline `return TRUE` with no PDB symbol; this tree
    declares IsSaveable on ten. When the nearest entry class in the chain is not one of those ten, a FALSE
    from us means "no override here", not "retail did not save it", and the object's bytes are still in the
    stream. Cached per UClass. */
static UBOOL DisIsSaveableAnswerTrusted( UClass* _pClass, FString& _rOutClass )
{
	static TMap<UClass*,INT>		Trusted;
	static TMap<UClass*,FString>	Blockers;

	if( _pClass == NULL )
	{
		return TRUE;
	}
	const INT* pCached = Trusted.Find( _pClass );
	if( pCached != NULL )
	{
		if( !*pCached )
		{
			_rOutClass = *Blockers.Find( _pClass );
		}
		return *pCached != 0;
	}

	// DISHONORED(written): agent EC - the whole chain is searched for a ported IsSaveable BEFORE the entry
	// list is consulted. Every subclass of a class that declares IsSaveable is itself a retail entry class,
	// because it inherits that vtable slot; stopping at the first entry class therefore called a class
	// untrusted whose answer its own base really does give. UDishonoredTask_Custom is the case that showed
	// it: UDishonoredTask_Base::IsSaveable is declared and conditional (SLL_FILE and inside an objectives
	// component), and the template tasks in Tower_Objectives are meant to be skipped.
	UBOOL bTrusted = FALSE;
	FString Blocker;
	for( UClass* pWalk = _pClass; pWalk != NULL; pWalk = pWalk->GetSuperClass() )
	{
		if( DisNameInList( pWalk->GetName(), GDisPortedIsSaveableClasses, ARRAY_COUNT(GDisPortedIsSaveableClasses) ) )
		{
			bTrusted = TRUE;
			break;
		}
	}
	if( !bTrusted )
	{
		bTrusted = TRUE;
		for( UClass* pWalk = _pClass; pWalk != NULL; pWalk = pWalk->GetSuperClass() )
		{
			const FString Name = pWalk->GetName();
			if( DisNameInList( Name, GDisRetailSaveEntryClasses, ARRAY_COUNT(GDisRetailSaveEntryClasses) ) )
			{
				bTrusted = FALSE;
				Blocker = Name;
				break;
			}
		}
	}
	Trusted.Set( _pClass, bTrusted ? 1 : 0 );
	if( !bTrusted )
	{
		Blockers.Set( _pClass, Blocker );
		_rOutClass = Blocker;
	}
	return bTrusted;
}

