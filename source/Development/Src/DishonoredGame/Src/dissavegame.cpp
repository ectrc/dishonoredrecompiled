// DISHONORED(bringup): retail spawns a tweaks-driven actor through UDisTweaksBase::SpawnActor
// (eDisTweaksSpawnType_InGame), which also runs the tweaks fixups and the spawn-type bookkeeping. This
// spawns m_pSpawnedObjectClass at the transform the dictionary recorded and hands the actor its tweaks,
// which is what the transform is for; the rest of retail's spawn path is a hand-over.
AActor* DisSpawnActorFromTweaks( UDisTweaksBase* _pTweaks, const FVector& _rLocation, const FRotator& _rRotation )
{
	if( _pTweaks == NULL || _pTweaks->m_pSpawnedObjectClass == NULL || GWorld == NULL )
	{
		return NULL;
	}
	AActor* pActor = GWorld->SpawnActor( _pTweaks->m_pSpawnedObjectClass, NAME_None, _rLocation, _rRotation, NULL, TRUE );
	if( pActor != NULL )
	{
		IDisTweaksInterface* pTweaksInterface = (IDisTweaksInterface*)pActor->GetInterfaceAddress( UDisTweaksInterface::StaticClass() );
		if( pTweaksInterface != NULL )
		{
			pTweaksInterface->SetTweaks( _pTweaks );
		}
	}
	return pActor;
}

// DISHONORED(written): one dictionary record's three parallel entries. The class and the is-a-class flag are
// what later records' shapes are read from, so they are kept even when the object itself did not resolve.
void FLevelLoader::AddRecord( UObject* _pObject, UClass* _pRecordClass, UBOOL _bIsClass )
{
	m_Objects.AddItem( _pObject );
	m_RecordClasses.AddItem( _pRecordClass );
	m_RecordIsClass.AddItem( _bIsClass );
	if( m_Objects.Num() > 3 )
	{
		GSaveLoadCensus.m_DictObjects++;
		if( _pObject != NULL )
		{
			m_NumResolved++;
		}
	}
}

// DISHONORED(port): 2013 rva 0x613070 (2012 0x658d80). The constructor is the whole pass, as retail's is.
FLevelLoader::FLevelLoader( FStringDictionary& _rStringDictionary, TArray<BYTE>& _rCompressedObjectData,
							TArray<BYTE>& _rCompressedObjectDictionary, ULevel* _pLevel, const FName& _rPackageName,
							ESaveLoadLocation _Location, WORD _NumObjects, WORD _NumSavedObjects,
							UBOOL _bReadUnshared, INT _SaveVersion )
:	FArchiveLoadCompressedProxy( _rCompressedObjectData, (ECompressionFlags)(COMPRESS_ZLIB|COMPRESS_BiasSpeed), 0x10000 )
,	m_rStringDictionary( _rStringDictionary )
,	m_Location( _Location )
,	m_bAborted( FALSE )
,	m_DataSize( GetUncompressedSize( _rCompressedObjectData ) )
,	m_DebugRecords( 0 )
,	m_DebugStreamObjects( 0 )
,	m_DebugStreamSeen( 0 )
,	m_NumResolved( 0 )
{
	Parse( appCmdLine(), TEXT("disdictdebug="), m_DebugRecords );
	Parse( appCmdLine(), TEXT("disstreamdebug="), m_DebugStreamObjects );
	ArIsPersistent		= FALSE;
	ArIsDisSaveLoad		= TRUE;
	ArVer				= _SaveVersion;
	// DISHONORED(port): 2013 rva 0x613070 - retail ORs PPF_ForceBinarySerialization into its own port flags
	// and into the dictionary loader's. It is the first disjunct of UByteProperty::SerializeItem (0x30830):
	// without it an enum ByteProperty is read BY NAME, four bytes through the string dictionary, where retail
	// wrote one raw byte - and every ported body that walks script properties binary reads such bytes.
	ArPortFlags		   |= PPF_ForceBinarySerialization;

	// the actors the save recorded as destroyed, read from the head of the object-data stream
	WORD NumDeletedActors = 0;
	ByteOrderSerialize( &NumDeletedActors, sizeof(NumDeletedActors) );
	for( WORD DeletedIdx = 0; DeletedIdx < NumDeletedActors; DeletedIdx++ )
	{
		FName LevelName = NAME_None;
		FName ObjectName = NAME_None;
		m_rStringDictionary.LoadFName( *this, LevelName );
		m_rStringDictionary.LoadFName( *this, ObjectName );
		ULevel* pDeletedLevel = DisFindLevelFromName( LevelName );
		AActor* pDeleted = Cast<AActor>( UObject::StaticFindObjectFast( AActor::StaticClass(), pDeletedLevel, ObjectName ) );
		if( pDeleted != NULL && GWorld != NULL )
		{
			GWorld->DestroyActor( pDeleted, FALSE, TRUE );
		}
	}

	// DISHONORED(port): 2013 rva 0x613070. Retail force-loads the player-item seek-free package when the
	// state is a file state, so that the pickups the dictionary is about to name resolve. It reads no stream
	// bytes. bLoadedSeekfree then forces a collection at the end of the restore.
	UBOOL bLoadedSeekfree = FALSE;
	if( GUseSeekFreeLoading && _Location == SLL_FILE )
	{
		UDishonoredInventory* pInventoryDefaults = UDishonoredInventory::StaticClass()->GetDefaultObject<UDishonoredInventory>();
		UObject::LoadPackage( NULL, *pInventoryDefaults->m_PlayerItem_SF_Package, LOAD_None );
		bLoadedSeekfree = TRUE;
	}

	m_Objects.Empty( _NumObjects );
	m_RecordClasses.Empty( _NumObjects );
	m_RecordIsClass.Empty( _NumObjects );
	AddRecord( NULL, NULL, FALSE );
	AddRecord( UPackage::StaticClass(), UClass::StaticClass(), TRUE );
	AddRecord( UPackage::StaticClass()->GetOuter(), UPackage::StaticClass(), FALSE );

	const UBOOL bSpawnActors = ( _Location == SLL_FILE ) || _bReadUnshared;

	{
		FArchiveLoadCompressedProxy ObjectDictionaryLoader( _rCompressedObjectDictionary,
			(ECompressionFlags)(COMPRESS_ZLIB|COMPRESS_BiasSpeed), 0x10000 );
		ObjectDictionaryLoader.SetVer( _SaveVersion );
		ObjectDictionaryLoader.SetPortFlags( ObjectDictionaryLoader.GetPortFlags() | PPF_ForceBinarySerialization );

		UBOOL bReadUnsharedObjects = _bReadUnshared;
		while( TRUE )
		{
			WORD Index = 0;
			ObjectDictionaryLoader.ByteOrderSerialize( &Index, sizeof(Index) );
			const UBOOL bValidIndex = ( Index != 0 && Index < m_Objects.Num() );
			UObject* pIndexed = bValidIndex ? m_Objects(Index) : NULL;
			UClass* pIndexedClass = bValidIndex ? m_RecordClasses(Index) : NULL;
			const UBOOL bIndexIsClass = bValidIndex ? m_RecordIsClass(Index) : FALSE;
			UObject* pObject = NULL;

			// the index names a DisTweaks object: the record is a spawn-on-load actor and carries a transform
			if( pIndexedClass != NULL && !bIndexIsClass && pIndexedClass->IsChildOf( UDisTweaksBase::StaticClass() ) )
			{
				UDisTweaksBase* pTweaks = Cast<UDisTweaksBase>( pIndexed );
				// a spawn-on-load actor: the dictionary carries its transform instead of its name
				FVector ActorLocation( 0.f, 0.f, 0.f );
				FRotator ActorRotation( 0, 0, 0 );
				ObjectDictionaryLoader << ActorLocation;
				ObjectDictionaryLoader << ActorRotation;
				if( bSpawnActors && pTweaks != NULL )
				{
					pObject = DisSpawnActorFromTweaks( pTweaks, ActorLocation, ActorRotation );
					if( pObject != NULL )
					{
						GSaveLoadCensus.m_Spawned++;
					}
				}
				AddRecord( pObject, pTweaks != NULL ? pTweaks->m_pSpawnedObjectClass : NULL, FALSE );
				continue;
			}

			// the index names a UClass: the record is an instance of it
			UClass* pClass = bIndexIsClass ? Cast<UClass>( pIndexed ) : NULL;
			if( bIndexIsClass && pClass != NULL )
			{
				BYTE bSpawnActorOnSaveGameLoad = 0;
				if( pClass->IsChildOf( AActor::StaticClass() ) )
				{
					ObjectDictionaryLoader.Serialize( &bSpawnActorOnSaveGameLoad, sizeof(bSpawnActorOnSaveGameLoad) );
				}
				if( bSpawnActorOnSaveGameLoad )
				{
					FVector ActorLocation( 0.f, 0.f, 0.f );
					FRotator ActorRotation( 0, 0, 0 );
					ObjectDictionaryLoader << ActorLocation;
					ObjectDictionaryLoader << ActorRotation;
					if( bSpawnActors && GWorld != NULL )
					{
						pObject = GWorld->SpawnActor( pClass, NAME_None, ActorLocation, ActorRotation, NULL, TRUE );
						if( pObject != NULL )
						{
							GSaveLoadCensus.m_Spawned++;
						}
					}
					AddRecord( pObject, pClass, FALSE );
					continue;
				}
				if( pClass->IsChildOf( ULevel::StaticClass() ) )
				{
					WORD LevelNameIdx = 0;
					ObjectDictionaryLoader.ByteOrderSerialize( &LevelNameIdx, sizeof(LevelNameIdx) );
					AddRecord( DisFindLevelFromName( m_rStringDictionary.GetName( LevelNameIdx ) ), pClass, FALSE );
					continue;
				}
			}

			// the general record: Outer, then the object's FName. Index 0 with Outer 0 is the terminator.
			WORD OuterIndex = 0;
			ObjectDictionaryLoader.ByteOrderSerialize( &OuterIndex, sizeof(OuterIndex) );
			if( Index == 0 && OuterIndex == 0 )
			{
				if( !bReadUnsharedObjects )
				{
					break;
				}
				bReadUnsharedObjects = FALSE;
				continue;
			}

			WORD NameIdx = 0;
			WORD NameNum = 0;
			ObjectDictionaryLoader.ByteOrderSerialize( &NameIdx, sizeof(NameIdx) );
			ObjectDictionaryLoader.ByteOrderSerialize( &NameNum, sizeof(NameNum) );
			const FName ObjectName( (EName)m_rStringDictionary.GetName( NameIdx ).GetIndex(), NameNum );
			UObject* pOuter = ( OuterIndex < m_Objects.Num() ) ? m_Objects(OuterIndex) : NULL;

			if( OuterIndex != 0 && pOuter == NULL )
			{
				pObject = NULL;
			}
			else
			{
				pObject = UObject::StaticFindObjectFast( pClass, pOuter, ObjectName );
			}
			if( pObject == NULL )
			{
				if( pClass != NULL && pClass->IsChildOf( UPackage::StaticClass() ) )
				{
					pObject = UObject::CreatePackage( pOuter, *ObjectName.ToString() );
				}
				else if( pOuter != NULL && pClass != NULL && pOuter->GetOutermost() != UObject::GetTransientPackage()
					&& !pOuter->IsInA( UWorld::StaticClass() ) )
				{
					// DISHONORED(port): 2013 rva 0x613070. The object lives in a content package this session
					// has not opened, and retail loads it before giving up. Under seek-free loading that means
					// the package's _SF variant; the retry then either finds the object or, for a tweaks class
					// whose package really is absent and when no actors are being spawned, marks the record
					// INVALID_OBJECT so that operator<< can tell "absent" from "not looked for".
					if( GUseSeekFreeLoading )
					{
						const FString SeekFreePackage = pOuter->GetOutermost()->GetName() + TEXT("_SF");
						if( UObject::LoadPackage( NULL, *SeekFreePackage, LOAD_SeekFree ) != NULL
							|| bSpawnActors
							|| !pClass->IsChildOf( UDisTweaksBase::StaticClass() ) )
						{
							pObject = UObject::StaticFindObjectFast( pClass, pOuter, ObjectName );
							bLoadedSeekfree = TRUE;
						}
						else
						{
							pObject = INVALID_OBJECT;
						}
					}
					else
					{
						pObject = UObject::StaticLoadObject( pClass, pOuter, *ObjectName.ToString(), NULL, LOAD_None, NULL );
					}
					if( pObject == NULL )
					{
						GSaveLoadCensus.m_NotFound++;
					}
				}
				else
				{
					// DISHONORED(port): 2013 rva 0x613070, the branch that falls through to
					// m_NotFoundObjects.Add. Retail remembers every record it did not retry through the package
					// loader - the outer is NULL, or transient, or inside a UWorld - because its class, outer and
					// name are all known and operator<<(UObject*&) can construct it the moment the data stream
					// names it. Agent EC: agent ED's port took this branch only for a NULL outer, so a
					// runtime-generated Kismet event duplicate inside a resolved sequence (AActor::GeneratedEvents;
					// records 40 and 47 of Dishonored0.sav) resolved to nothing and stopped the restore.
					FObjectRef Ref;
					Ref.m_pClass		= pClass;
					Ref.m_OuterIndex	= OuterIndex;
					Ref.m_Name			= ObjectName;
					m_NotFoundObjects.Set( (WORD)m_Objects.Num(), Ref );
					GSaveLoadCensus.m_NotFound++;
				}
			}
			// a record written with class index 0 *is* a UClass (GetObjectIndex, 2013 rva 0x611b80), which is
			// what later records read their own shape from
			AddRecord( pObject, Index == 0 ? UClass::StaticClass() : pClass, Index == 0 );
			if( GSaveLoadCensus.m_DictObjects <= m_DebugRecords )
			{
				warnf( TEXT("DisDict %5d: idx %5d class %-28s name %-28s outer %5d -> %s"),
					m_Objects.Num() - 1, (INT)Index,
					pClass != NULL ? *pClass->GetName() : TEXT("<none>"),
					*ObjectName.ToString(), (INT)OuterIndex,
					pObject != NULL ? *pObject->GetPathName() : TEXT("NOT FOUND") );
			}
		}
		GSaveLoadCensus.m_DictBytesRead += ObjectDictionaryLoader.Tell();
	}
	GSaveLoadCensus.m_DictBytesExpected += GetUncompressedSize( _rCompressedObjectDictionary );
	GSaveLoadCensus.m_DictExpected += _NumObjects;
	GSaveLoadCensus.m_DictResolved += m_NumResolved;
	_rCompressedObjectDictionary.Empty();

	// the object states
	UObject* pObject = NULL;
	do
	{
		*this << pObject;
	}
	while( pObject != NULL && !m_bAborted );

	if( _bReadUnshared && !m_bAborted )
	{
		do
		{
			*this << pObject;
		}
		while( pObject != NULL && !m_bAborted );
	}

	GSaveLoadCensus.m_DataBytesRead += Tell();
	GSaveLoadCensus.m_DataBytesExpected += GetUncompressedSize( _rCompressedObjectData );
	GSaveLoadCensus.m_NumLevels++;

	if( !m_bAborted && _pLevel != NULL )
	{
		USequence* pGameSequence = _pLevel->GetGameSequence();
		if( pGameSequence != NULL )
		{
			InitializeSequencePostLoad( pGameSequence );
		}
	}

	// DISHONORED(port): 2013 rva 0x613070 tail. Everything the dictionary pulled in on demand is a candidate
	// for collection the moment the restore is over.
	if( bLoadedSeekfree && GWorld != NULL && GWorld->GetWorldInfo() != NULL )
	{
		GWorld->GetWorldInfo()->ForceGarbageCollection( TRUE );
	}
}

