// DISHONORED(port): 2013 rva 0x60c930 (2012 0x653700). A WORD dictionary index; the top bit means the
// object belongs to an unshared sub-level, so its state is not in this stream.
FArchive& FLevelLoader::operator<<( UObject*& _rpObject )
{
	if( m_bAborted )
	{
		_rpObject = NULL;
		return *this;
	}

	WORD ObjIndex = 0;
	ByteOrderSerialize( &ObjIndex, sizeof(ObjIndex) );
	UBOOL bDeferred = FALSE;
	if( ( ObjIndex & 0x8000 ) != 0 )
	{
		ObjIndex &= 0x7FFF;
		bDeferred = TRUE;
	}

	if( ObjIndex == 0 )
	{
		_rpObject = NULL;
		return *this;
	}

	FObjectRef* pRef = m_NotFoundObjects.Find( ObjIndex );
	if( pRef != NULL )
	{
		UObject* pOuter = ( pRef->m_OuterIndex < m_Objects.Num() ) ? m_Objects(pRef->m_OuterIndex) : NULL;
		_rpObject = UObject::StaticFindObjectFast( pRef->m_pClass, pOuter, pRef->m_Name );
		if( _rpObject == NULL && pRef->m_pClass != NULL )
		{
			_rpObject = UObject::StaticConstructObject( pRef->m_pClass, pOuter, pRef->m_Name );
		}
		if( ObjIndex < m_Objects.Num() )
		{
			m_Objects(ObjIndex) = _rpObject;
		}
		m_NotFoundObjects.Remove( ObjIndex );
	}
	else
	{
		_rpObject = ( ObjIndex < m_Objects.Num() ) ? m_Objects(ObjIndex) : NULL;
	}

	if( bDeferred )
	{
		// the reference belongs to an unshared sub-level: its state is in that level's own stream, not here
		GSaveLoadCensus.m_ObjectsSkipped++;
		return *this;
	}
	if( _rpObject == NULL )
	{
		// retail cannot reach this - ShouldLoadObject dereferences the object with no NULL check, because in
		// the session that wrote the save everything the dictionary named was resident. Here it is common, and
		// skipping the object reads none of the bytes retail wrote for it, so the rest of the stream is lost.
		GSaveLoadCensus.m_NullObjects++;
		if( !GSaveLoadCensus.m_bDesynchronised )
		{
			GSaveLoadCensus.m_bDesynchronised = TRUE;
			warnf( NAME_Warning, TEXT("DisSaveLoad: stopping the level restore at dictionary index %d, which resolved to no live object in this session: retail wrote that object's state inline with no length prefix, so its bytes cannot be skipped. %d objects were restored first."),
				(INT)ObjIndex, GSaveLoadCensus.m_ObjectsRestored );
		}
		m_bAborted = TRUE;
		return *this;
	}

	// the safety net: retail wrote this object's state with the first override in its class chain. If that
	// is one this tree does not have, reading on would misread every object after it.
	FString BlockingClass;
	const EDisSaveClassState State = DisClassifySaveClass( _rpObject->GetClass(), BlockingClass );
	if( State == DSCS_Unported )
	{
		GSaveLoadCensus.m_UnportedClasses++;
		if( !GSaveLoadCensus.m_bDesynchronised )
		{
			GSaveLoadCensus.m_bDesynchronised = TRUE;
			warnf( NAME_Warning, TEXT("DisSaveLoad: stopping the level restore at '%s' (%s): its GameLoad is one of the %d retail overrides this tree has not ported, and the object stream carries no length prefix, so reading on would desynchronise it. %d objects were restored first."),
				*_rpObject->GetPathName(), *BlockingClass,
				(INT)ARRAY_COUNT(GDisUnportedGameLoadClasses), GSaveLoadCensus.m_ObjectsRestored );
		}
		m_bAborted = TRUE;
		_rpObject = NULL;
		return *this;
	}

	if( ShouldLoadObject( _rpObject ) )
	{
		m_LoadedObjects.Add( _rpObject );
		_rpObject->GameLoad( *this, m_Location );
		GSaveLoadCensus.m_ObjectsRestored++;
		return *this;
	}

	// not saveable here - but is that retail's answer or a missing IsSaveable? If retail treats the class as
	// an entry point and this tree has no IsSaveable of its own anywhere in the chain, the object's bytes are
	// in the stream and skipping it loses everything after it.
	FString EntryClass;
	if( !m_LoadedObjects.Contains( _rpObject ) && !DisIsSaveableAnswerTrusted( _rpObject->GetClass(), EntryClass ) )
	{
		GSaveLoadCensus.m_UntrustedSkips++;
		if( !GSaveLoadCensus.m_bDesynchronised )
		{
			GSaveLoadCensus.m_bDesynchronised = TRUE;
			warnf( NAME_Warning, TEXT("DisSaveLoad: stopping the level restore at '%s': retail treats %s as a save entry point (its IsSaveable is one of the 59 inline `return TRUE` bodies its linker folded away) and this tree declares none in that chain, so its state is in the stream and cannot be skipped. %d objects were restored first."),
				*_rpObject->GetPathName(), *EntryClass, GSaveLoadCensus.m_ObjectsRestored );
		}
		m_bAborted = TRUE;
		_rpObject = NULL;
		return *this;
	}

	GSaveLoadCensus.m_ObjectsSkipped++;
	return *this;
}

