{
}

// DISHONORED(written): after an abort the stream must go quiet. A ported body that has already been
// entered keeps reading plain data after one of its object references aborts, and a garbage count there
// is how UDishonoredMapInfo::GameLoad died in a 16 MB FString. Retail has no such override and needs
// none, because it cannot abort. The byte count is Tell(), not a counter here: the proxy's own Serialize
// calls itself recursively to cross its buffer boundary, so a counter in an override double-counts.
void FLevelLoader::Serialize( void* _pData, INT _Count )
{
	if( m_bAborted )
	{
		appMemzero( _pData, _Count );
		return;
	}
	FArchiveLoadCompressedProxy::Serialize( _pData, _Count );
}

