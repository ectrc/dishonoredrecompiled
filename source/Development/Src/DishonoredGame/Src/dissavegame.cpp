// DISHONORED(port): 2012 rva 0x8ef4d0 (disattributes.cpp:431). Three floats, then one packed byte, then the
// modifier map only when it has entries; m_fCachedModifiedValue is not in the stream and on load
// m_bCachedValueIsDirty is forced TRUE so the value is recomputed.
FArchive& operator<<( FArchive& _rArchive, FDisModifiedAttribute& _rModifiedAttribute )
{
	_rArchive << _rModifiedAttribute.m_fAttributeBaseValue;
	_rArchive << _rModifiedAttribute.m_fMinRange;
	_rArchive << _rModifiedAttribute.m_fMaxRange;

	UBOOL bHasModifiers = FALSE;
	if( _rArchive.IsLoading() )
	{
		BYTE Bools = 0;
		_rArchive.Serialize( &Bools, sizeof(Bools) );
		bHasModifiers = ( Bools & 0x02 ) != 0;
		_rModifiedAttribute.m_bEnforceRange = ( Bools & 0x01 ) ? 1 : 0;
		_rModifiedAttribute.m_bCachedValueIsDirty = 1;
	}
	else
	{
		bHasModifiers = _rModifiedAttribute.m_Modifiers.Num() > 0;
		BYTE Bools = (BYTE)( ( _rModifiedAttribute.m_bEnforceRange ? 0x01 : 0 ) | ( bHasModifiers ? 0x02 : 0 ) );
		_rArchive.Serialize( &Bools, sizeof(Bools) );
	}
	if( bHasModifiers )
	{
		_rArchive << _rModifiedAttribute.m_Modifiers;
	}
	return _rArchive;
}

