/**
 * DISHONORED(port): 2013 rva 0xc7210 (2012 0xc3480, akbank.cpp:23). The file-package name is the bank name
 * plus ".pck", except for a seek-free "BK_" bank, which is "<name>.<language>" - and the language there is
 * remapped once per run: POL, CZE and HUN all ship the Russian voice set, so their suffix is RUS.
 * With the package registered, a bank whose GenerateDefinition flag is set (and outside the editor) is only
 * *prepared* - metadata without media - which is the seek-free path; everything else is loaded outright.
 */
static const FString& AkBankLanguageSuffix()
{
	// DISHONORED(retail): retail keeps this in two file statics (a once flag and an FString) initialised at
	// the top of UAkBank::Load; a function-local static is the same thing without the flag.
	static UBOOL bInitialized = FALSE;
	static FString Language;
	if( !bInitialized )
	{
		Language = UObject::GetLanguage();
		if( Language == TEXT("POL") || Language == TEXT("CZE") || Language == TEXT("HUN") )
		{
			Language = TEXT("RUS");
		}
		bInitialized = TRUE;
	}
	return Language;
}

/** TRUE when the file package was registered (AK_Success, or already loaded / language-less). */
static UBOOL AkBankLoadFilePackage( UAkBank* Bank, UAkAudioDevice* AudioDevice, AkUInt32& OutPackageID )
{
	const FString BankName = Bank->GetName();
	FString PackageName;
	if( GUseSeekFreeLoading && BankName.Left(3).ToUpper() == TEXT("BK_") )
	{
		PackageName = FString::Printf( TEXT("%s.%s"), *BankName, *AkBankLanguageSuffix() );
	}
	else
	{
		PackageName = BankName + AKPACKAGEFILEEXTENSION;
	}
	const AKRESULT Result = AudioDevice->LoadFilePackage( *PackageName, OutPackageID );
	// DISHONORED(retail): retail accepts AK_Success and AK_InvalidLanguage (0xc7210 compares 1 and 22); a
	// package this run already registered comes back as AK_BankAlreadyLoaded from our own layer.
	return Result == AK_Success || Result == AK_InvalidLanguage || Result == AK_BankAlreadyLoaded;
}

UBOOL UAkBank::Load()
{
	if( !GEngine || !GEngine->bUseSound || GIsCooking )
	{
		return FALSE;
	}
	UAkAudioDevice* AudioDevice = UAkAudioDevice::Get();
	if( !AudioDevice )
	{
		return FALSE;
	}
	AkUInt32 PackageID = 0;
	if( !AkBankLoadFilePackage( this, AudioDevice, PackageID ) )
	{
		return FALSE;
	}
	m_AkPackageID = (INT)PackageID;
	const FString BankName = GetName();
	AKRESULT Result;
	if( !GIsEditor && GenerateDefinition )
	{
		Result = AudioDevice->PrepareBank( AK::SoundEngine::Preparation_Load, *BankName, AK::SoundEngine::AkBankContent_StructureOnly );
	}
	else
	{
		AkBankID BankID = AK_INVALID_BANK_ID;
		Result = AudioDevice->LoadBank( *BankName, AK_DEFAULT_POOL_ID, BankID );
	}
	return Result == AK_Success;
}

