UBOOL UAkBank::LoadAsync( void* Callback, void* Cookie )
{
	if( !GEngine || !GEngine->bUseSound || GIsCooking )
	{
		return FALSE;
	}
	UAkAudioDevice* AudioDevice = UAkAudioDevice::Get();
	if( !AudioDevice )
	{
		return FALSE;
	}
	AkUInt32 PackageID = 0;
	if( !AkBankLoadFilePackage( this, AudioDevice, PackageID ) )
	{
		return FALSE;
	}
	m_AkPackageID = (INT)PackageID;
	const FString BankName = GetName();
	AkBankID BankID = AK_INVALID_BANK_ID;
	return AudioDevice->LoadBank( *BankName, (AkBankCallbackFunc)Callback, Cookie, AK_DEFAULT_POOL_ID, BankID ) == AK_Success;
}

// DISHONORED(port): 2013 rva 0xc7680: unload (or unprepare) the bank, then release its file package
void UAkBank::Unload()
{
	if( !GEngine || !GEngine->bUseSound || GIsCooking || !m_AkPackageID )
	{
		return;
	}
	UAkAudioDevice* AudioDevice = UAkAudioDevice::Get();
	if( !AudioDevice )
	{
		return;
	}
	const FString BankName = GetName();
	if( !GIsEditor && GenerateDefinition )
	{
		AudioDevice->PrepareBank( AK::SoundEngine::Preparation_Unload, *BankName, AK::SoundEngine::AkBankContent_StructureOnly );
	}
	else
	{
		AudioDevice->UnloadBank( *BankName, (AkMemPoolId*)NULL );
	}
	AudioDevice->UnloadFilePackage( (AkUInt32)m_AkPackageID );
	m_AkPackageID = 0;
}

